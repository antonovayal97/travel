function hashSeed(input: string): number {
  let hash = 0
  for (let i = 0; i < input.length; i += 1) {
    hash = (hash * 31 + input.charCodeAt(i)) >>> 0
  }
  return hash
}

export function pickTravelImage(
  country: string,
  region: string,
  seed = '',
): TravelImage {
  const pool =
    regionImagePools[region] ||
    countryImagePools[country] ||
    countryImagePools['Вьетнам']
  const index = hashSeed(`${seed}|${region}|${country}`) % pool.length
  return pool[index]!
}
